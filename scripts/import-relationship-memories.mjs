// Helper to escape SQL strings
function esc(str) {
  if (!str) return "''";
  return "'" + str.replace(/'/g, "''") + "'";
}

export function generateMigrationSQL() {
  const statements = [];

  // 1. Alter table to ensure columns exist
  statements.push(`-- Ensure expanded columns exist in memories table`);
  statements.push(`ALTER TABLE memories ADD COLUMN approx_date TEXT;`);
  statements.push(`ALTER TABLE memories ADD COLUMN status TEXT DEFAULT 'confirmed';`);
  statements.push(`ALTER TABLE memories ADD COLUMN source_type TEXT DEFAULT 'her_statement';`);
  statements.push(`ALTER TABLE memories ADD COLUMN related_keys TEXT;`);

  // 2. Remove obsolete generic placeholder seed memories
  statements.push(`\n-- Clean up obsolete generic template seeds if present`);
  statements.push(`DELETE FROM memories WHERE title LIKE '%Photography & Golden Hour Walks%' OR title LIKE '%Matcha Lattes & Thai Green Curry%' OR title LIKE '%Late Replies Without Notice & Crowded Malls%' OR title LIKE '%The Penguin Waddle%';`);

  // 3. Insert all relationship memories idempotently
  const now = new Date().toISOString();
  statements.push(`\n-- Insert comprehensive relationship memories vault`);
  for (const m of RELATIONSHIP_MEMORIES) {
    statements.push(`INSERT OR IGNORE INTO memories (category, title, content, emotional_significance, approx_date, status, source_type, related_keys, source, created_at, updated_at) VALUES (${esc(m.category)}, ${esc(m.title)}, ${esc(m.content)}, ${esc(m.emotional_significance)}, ${esc(m.approx_date)}, ${esc(m.status)}, ${esc(m.source_type)}, ${esc(m.related_keys)}, 'manual', '${now}', '${now}');`);
  }

  // 4. Update important dates: Official anniversary
  statements.push(`\n-- Ensure official anniversary is in important_dates`);
  statements.push(`INSERT OR IGNORE INTO important_dates (title, event_date, category, reminder_days_before, notes, is_recurring_yearly, created_at) VALUES ('Our Relationship Anniversary (Started Texting)', '2024-03-16', 'anniversary', 14, 'March 16, 2024 is the day we first started texting and our official anniversary date we count as ours.', 1, '${now}');`);
  statements.push(`INSERT OR IGNORE INTO important_dates (title, event_date, category, reminder_days_before, notes, is_recurring_yearly, created_at) VALUES ('Reconnection & Grilled Cheese Coincidence', '2024-03-30', 'special_occasion', 7, 'Reconnected after ~2 years apart and both ate grilled cheese sandwiches at the exact same moment before becoming official.', 1, '${now}');`);

  return statements.join('\n');
}

// If run directly via node:
if (process.argv[1] && process.argv[1].endsWith('import-relationship-memories.mjs')) {
  console.log(`Generated ${RELATIONSHIP_MEMORIES.length} structured relationship memories.`);
  const sql = generateMigrationSQL();
  const sqlPath = path.resolve('migrations', '0002_import_comprehensive_memories.sql');
  fs.writeFileSync(sqlPath, sql, 'utf8');
  console.log(`Saved SQL migration file to: ${sqlPath}`);
}
